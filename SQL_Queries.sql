4.Find the Top 10 customers by spending.
SELECT
CUSTOMER_NAME,
MAX(TOTAL_SPEND) AS HIGHEST_SPEND
FROM CUSTOMERS
GROUP BY CUSTOMER_NAME
ORDER BY MAX(TOTAL_SPEND)  DESC
LIMIT 10

